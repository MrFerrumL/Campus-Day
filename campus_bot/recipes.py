def video_url(name):
    return 'https://www.youtube.com/results?search_query=' + quote_plus(name + ' рецепт')


def _build(row):
    uid, name, meal, minutes, servings, ingredients, steps = row
    found = [nutrition.count(line) for line in ingredients]
    total = {k: sum(r['total'][k] for r in found) for k in ('calories', 'protein', 'fat', 'carbs')}
    per = {k: round(v / servings) if k == 'calories' else round(v / servings, 1) for k, v in total.items()}
    tags = [MEALS[meal]]
    if minutes <= QUICK_MINUTES:
        tags.append('Быстро')
    if per['protein'] >= HIGH_PROTEIN:
        tags.append('Много белка')
    if per['calories'] <= LIGHT_KCAL:
        tags.append('Лёгкое')
    return dict(id=uid, name=name, meal=meal, minutes=minutes, servings=servings, ingredients=list(ingredients),
                steps=list(steps), tags=tags, video=video_url(name), unknown=[u for r in found for u in r['unknown']], **per)


@lru_cache(maxsize=1)
def _catalog():
    return tuple(_build(row) for row in RECIPES)


def catalog():
    """Every recipe with per-serving calories and macros (fresh copies, safe to change)."""
    return [dict(r, ingredients=list(r['ingredients']), steps=list(r['steps']), tags=list(r['tags']), unknown=list(r['unknown']))
            for r in _catalog()]


def find(uid):
    return next((r for r in catalog() if r['id'] == uid), None)


def describe(recipe):
    """A recipe as chat text."""
    lines = [f'🍳 {recipe["name"].upper()}', f'⏱ {recipe["minutes"]} мин · порций: {recipe["servings"]}',
             f'На порцию: {recipe["calories"]} ккал · Б {recipe["protein"]:g} · Ж {recipe["fat"]:g} · У {recipe["carbs"]:g} г', '',
             'Продукты:'] + [f'• {i}' for i in recipe['ingredients']] + ['', 'Как готовить:']
    lines += [f'{n}. {s}' for n, s in enumerate(recipe['steps'], 1)]
    return '\n'.join(lines)
